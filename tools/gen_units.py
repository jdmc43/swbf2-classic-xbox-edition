"""Generate compat/xboxpicker/units.lua: class -> body mesh, weapon mesh, animation set,
from the installed side .lvl files (so Remaster model changes are respected).
usage: gen_units.py <sides.json from sideclasses.py> [out units.lua] [out units.lua]
"""
import json, sys

d = json.load(open(sys.argv[1]))


def res(c, p):
    seen = 0
    while c in d and seen < 25:
        v = d[c]["props"].get(p)
        if v:
            return v
        c = d[c]["parent"]
        seen += 1
    return None


def hero_weapons(cls):
    """heroes list their weapons under per-slot keys (hashed names in sides.json): every value naming a
    weapon class, child classes first, in file order"""
    out = []
    c, seen = cls, 0
    while c in d and seen < 25:
        for vals in d[c]["props"].values():
            for v in vals:
                if v in d and d[v]["kind"] == "wpnc" and v not in out:
                    out.append(v)
        c = d[c]["parent"]
        seen += 1
    return out


def weapon_key(w):
    """localization key of a weapon class: rep_weap_inf_rifle -> weapons.rep.weap.inf_rifle"""
    side, rest = w.split("_", 1)
    return "weapons.%s.weap.%s" % (side, rest[5:] if rest.startswith("weap_") else rest)


# the installer's rep.lvl fix (tools/sidepatch.py): the commando/award pistol shows the DC-17 model; the ring
# shows the same whether the side file is patched yet or not
GEOM_FIX = {"rep_weap_inf_smallpistol": "rep_weap_inf_pistol"}


def chain(c):
    out = []
    while c in d and len(out) < 25:
        out.append(c)
        c = d[c]["parent"]
    return out


lines = ["-- generated by tools/gen_units.py from the installed side files", "XBPICK_UNITS = {"]
n = 0
for cls in sorted(d):
    if d[cls]["kind"] != "entc":
        continue
    ch = chain(cls)
    if not any(("_inf_" in c or "_hero_" in c) for c in ch) or "_weap_" in cls:
        continue
    body = (res(cls, "GeometryName") or [None])[0]
    weaps = res(cls, "WeaponName") or []
    if not body:
        continue
    hero = "_hero_" in cls
    hw = hero_weapons(cls) if hero and not weaps else []
    if hw:
        weaps = hw
    weap = weaps[0] if weaps else None
    wmesh = (res(weap, "GeometryName") or [None])[0] if weap else None
    wmesh = GEOM_FIX.get(wmesh, wmesh)
    skel = ((res(cls, "SkeletonName") or [""])[0] or "").lower()
    anim = ((res(cls, "AnimationName") or [""])[0] or "").lower()
    wchain = " ".join(chain(weap)) if weap else ""
    launcher = any(k in wchain for k in ("launcher", "rocket", "mortar", "bazooka"))
    combo = ((res(weap, "ComboAnimationBank") or [""])[0] or "").lower() if weap else ""
    sabre = "sabre" in combo or "saber" in wchain or "sabre" in wchain
    if sabre:  # lightsaber heroes hold the saber (ring.lua XBRING_ANIMS.sabre/doublesabre)
        a = "doublesabre" if "double" in wchain else "sabre"
    elif anim == "cis_walk_droideka" or "droideka" in body.lower():
        a = "droideka"
    elif skel == "sbdroid":
        a = "sbdroid"
    elif skel in ("bdroid", "magnaguard", "wookie", "marksperson"):
        a = skel + ("_bazooka" if launcher else "")
    else:
        a = "bazooka" if launcher else "rifle"
    w = '"%s"' % wmesh if wmesh else "nil"
    t1 = (res(cls, "OverrideTexture") or [None])[0]
    t2 = (res(cls, "OverrideTexture2") or [None])[0]
    tex = (', t1 = "%s"' % t1 if t1 else "") + (', t2 = "%s"' % t2 if t2 else "")
    if hero and weaps:  # the exe leaves the hero slot's texts empty: equipment for the picker window
        tex += ', e = { %s }' % ", ".join('"%s"' % weapon_key(x) for x in weaps)
    lines.append('\t["%s"] = { b = "%s", w = %s, a = "%s"%s },' % (cls.lower(), body, w, a, tex))
    n += 1
lines.append("}")
open(sys.argv[2] if len(sys.argv) > 2 else "compat/xboxpicker/units.lua", "w").write("\n".join(lines) + "\n")
print("units:", n)
